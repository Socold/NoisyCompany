"""Generate the browser companion's persona list and manifest (feature `browser_companion`).

The WebExtension in companion/ reuses the same reviewed personas as the daemon. This
module is the single source: `noisycompany companion export` writes personas.js and
manifest.json (host permissions = exactly the persona domains, nothing broader), and
`--check` fails in CI when the committed files are stale.

Two manifests come out of the same sources: Firefox (event page, containers for tab
mode) and Chromium (service worker, no containers, so no tab mode).
"""

from __future__ import annotations

import json
import tomllib
from importlib import resources
from pathlib import Path
from typing import Any

from noisycompany import __version__, packs

# File -> locale tag; the popup lets the user choose which locales to use.
PERSONA_FILES = {"personas.toml": "en", "personas_fr.toml": "fr", "personas_de.toml": "de",
                 "personas_es.toml": "es", "personas_it.toml": "it"}
# Opt-in link to the daemon dashboard (read-only status), requested at runtime only.
DAEMON_PERMISSION = "http://127.0.0.1/*"


def companion_personas() -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for name, locale in PERSONA_FILES.items():
        text = resources.files("noisycompany.data").joinpath(name).read_text("utf-8")
        data = tomllib.loads(text)
        if packs.validate(data, require_meta=False):
            raise ValueError(f"{name} does not pass the pack validator")
        for k, v in data.items():
            out[k] = {"seeds": v["seeds"], "domains": v["domains"], "locale": locale}
    return dict(sorted(out.items()))


def manifest(personas: dict[str, dict[str, Any]], target: str = "firefox") -> dict[str, Any]:
    domains = sorted({d for p in personas.values() for d in p["domains"]})
    version = __version__.split("a")[0].split("b")[0]
    base = {
        "manifest_version": 3,
        "name": "NoisyCompany companion",
        "version": version,
        "description": "Rare, light decoy visits from your own browser. Off by default, "
                       "no ads, no clicks, no data collected.",
        "browser_specific_settings": {
            "gecko": {"id": "companion@noisycompany", "strict_min_version": "128.0",
                      "data_collection_permissions": {"required": ["none"]}},
        },
        "background": {"scripts": ["compat.js", "lib.js", "personas.js", "background.js"]},
        "action": {"default_popup": "popup.html", "default_title": "NoisyCompany"},
        "permissions": ["alarms", "storage", "idle", "contextualIdentities", "cookies"],
        "host_permissions": [f"https://{d}/*" for d in domains],
        "optional_host_permissions": [DAEMON_PERMISSION],
        "content_security_policy": {
            "extension_pages": "script-src 'self'; object-src 'none'; base-uri 'none'"},
    }
    if target == "chromium":
        del base["browser_specific_settings"]
        base["background"] = {"service_worker": "sw.js"}
        base["permissions"] = ["alarms", "storage", "idle"]  # no containers: no tab mode
        base["minimum_chrome_version"] = "120"
    return base


def render() -> dict[str, str]:
    personas = companion_personas()
    js = ("// Generated by `noisycompany companion export`. Do not edit.\n"
          f"globalThis.NC_PERSONAS = {json.dumps(personas, indent=2, ensure_ascii=False)};\n")
    return {"personas.js": js,
            "manifest.json": json.dumps(manifest(personas), indent=2) + "\n",
            "manifest.chromium.json": json.dumps(manifest(personas, "chromium"), indent=2) + "\n"}


def export(target: Path, check: bool = False) -> list[str]:
    """Write files (or, with check, return the names of stale ones)."""
    stale = []
    for name, content in render().items():
        path = target / name
        current = path.read_text("utf-8") if path.exists() else None
        if current != content:
            stale.append(name)
            if not check:
                path.write_text(content, "utf-8")
    return stale
